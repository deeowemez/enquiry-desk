#!/usr/bin/env python3
"""Score the Enquiry Desk against test/enquiries.jsonl.

Sends every test case to the n8n webhook, waits for the workflow to write its
`enquiry` row, and compares what was stored with what was expected.

    python3 test/score.py \
        --webhook https://<your-n8n>/webhook/enquiry \
        --psql "psql postgresql://user:pass@localhost:5432/dbname"

    # Postgres inside Docker:
    --psql "docker compose -f ~/repos/enquiry-desk/docker-compose.yml exec -T postgres psql -U <user> -d <db>"

    # Run a few cases first:
    --only t01,t04,t18

    # Name the run (which models / prompts produced it) so test/compare.py can tell runs apart:
    --label "nova-2-lite all stages"

The workflow must be ACTIVE and you must use a PRODUCTION-mode webhook URL (the live one, or the
staging copy's `/webhook/enquiry-staging` from test/staging.py). The test URL only accepts one
request, and pinned data is ignored in production anyway.

Standard library only. Exit code 1 if a safety case is missed or category
accuracy falls below --min-accuracy, so this can gate changes later.
"""
import argparse
import datetime
import json
import pathlib
import re
import shlex
import subprocess
import sys
import time
import urllib.error
import urllib.request

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
SEP = "\x1f"  # field separator for psql output; never appears in our data


def post(url, payload):
    req = urllib.request.Request(
        url, data=json.dumps(payload).encode(),
        headers={"content-type": "application/json"}, method="POST")
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return r.status
    except urllib.error.HTTPError as e:
        return e.code
    except urllib.error.URLError as e:
        sys.exit(f"Could not reach the webhook: {e.reason}\n"
                 "Is the workflow active, and is this the PRODUCTION URL?")


def query(psql, sql):
    # SQL goes on stdin, not -c: ssh re-splits remote args, which breaks multi-line SQL
    cmd = shlex.split(psql) + ["-At", "-F", SEP]
    out = subprocess.run(cmd, input=sql, capture_output=True, text=True)
    if out.returncode != 0:
        sys.exit(f"psql failed:\n{out.stderr.strip()}")
    return [line.split(SEP) for line in out.stdout.splitlines() if line]


def fetch(psql, email):
    # email is generated by this script, so it is safe to inline
    sql = f"""
      select e.category, e.confidence, e.language,
             e.safety_flags::text, e.missing_slots::text, coalesce(e.action, ''),
             -- only replies that would reach the customer: blocked ones never leave
             coalesce((select replace(r.body, E'\\n', ' ') from reply r
                        where r.enquiry_id = e.id and not r.blocked limit 1), ''),
             coalesce((select sum(cost_usd) from run_log l
                        where l.enquiry_id = e.id), 0),
             e.status
      from enquiry e where e.from_email = '{email}'
        -- the row is written on arrival ('received'); wait until the run has finished with it
        and e.status in ('processed', 'failed')"""
    rows = query(psql, sql)
    if not rows:
        return None
    cat, conf, lang, flags, slots, action, reply, cost, status = rows[0]
    return {
        "status": status,
        "category": cat,
        "confidence": float(conf) if conf else None,
        "language": lang,
        "safety_flags": json.loads(flags or "[]"),
        "missing_slots": json.loads(slots or "[]"),
        "action": action or None,
        "reply": reply or None,
        "cost_usd": float(cost or 0),
    }


def wait_for(psql, email, timeout):
    deadline = time.time() + timeout
    while time.time() < deadline:
        row = fetch(psql, email)
        if row:
            return row
        time.sleep(1.5)
    return None


def allowed_numbers():
    """Every number that appears anywhere in the fact table."""
    text = (ROOT / "kb" / "facts.yaml").read_text()
    return set(re.findall(r"\d+(?:\.\d+)?", text))


def invented_prices(reply, allowed):
    claimed = [re.sub(r"[^\d.]", "", m)
               for m in re.findall(r"[£$]\s?\d+(?:\.\d+)?", reply or "")]
    return [n for n in claimed if n not in allowed]


def real_flags(flags):
    return {f for f in flags if f != "none"}


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--webhook", required=True, help="PRODUCTION-mode webhook URL (live or staging)")
    ap.add_argument("--label", default="",
                    help="name for this run, stored in the results file (e.g. the model set)")
    ap.add_argument("--psql", required=True, help="command that opens psql on the right database")
    ap.add_argument("--only", help="comma-separated case ids, e.g. t01,t18")
    ap.add_argument("--delay", type=float, default=6,
                    help="seconds between cases (free tier rate-limits; default 6)")
    ap.add_argument("--timeout", type=float, default=120,
                    help="seconds to wait for each enquiry row (default 120)")
    ap.add_argument("--min-accuracy", type=float, default=0.0,
                    help="fail if category accuracy is below this, e.g. 0.85")
    args = ap.parse_args()

    cases = [json.loads(l) for l in (HERE / "enquiries.jsonl").read_text().splitlines() if l.strip()]
    if args.only:
        want = {x.strip() for x in args.only.split(",")}
        cases = [c for c in cases if c["id"] in want]
    if not cases:
        sys.exit("No matching cases.")

    run = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    allowed = allowed_numbers()
    results = []

    print(f"Run {run} — {len(cases)} cases, {args.delay:.0f}s apart" +
          (f" — {args.label}" if args.label else "") + "\n")
    print(f"{'id':4} {'expected':24} {'got':24} {'ok':3} {'conf':5} {'flags':18} note")
    print("-" * 100)

    for i, case in enumerate(cases):
        exp = case["expect"]
        email = f"test+{run}-{case['id']}@example.com"   # unique per run: no dedupe collisions
        status = post(args.webhook, {"email": email, "subject": "", "message": case["body"]})

        got = wait_for(args.psql, email, args.timeout) if status < 400 else None
        r = {"id": case["id"], "label": args.label, "note": case.get("note"), "expect": exp,
             "http_status": status, "got": got}

        if got is not None and got["status"] == "failed":
            r["verdict"] = "failed"
            print(f"{case['id']:4} {exp['category']:24} {'— (FAILED)':24} {'✗':3} {'':5} {'':18} "
                  f"run failed; row is in dead_letter")
            got = r["got"] = None
        elif got is None:
            r["verdict"] = "no row"
            print(f"{case['id']:4} {exp['category']:24} {'— (no row)':24} {'✗':3} {'':5} {'':18} "
                  f"HTTP {status}; check the n8n Executions list")
        else:
            r["category_ok"] = got["category"] == exp["category"]

            if "safety_flags" in exp:
                want_flags = real_flags(exp["safety_flags"])
                r["safety_ok"] = (want_flags <= real_flags(got["safety_flags"])) if want_flags \
                    else not real_flags(got["safety_flags"])

            if "missing_slots" in exp:
                r["slots_ok"] = set(exp["missing_slots"]) == set(got["missing_slots"])

            if "language" in exp:
                r["language_ok"] = (got["language"] or "")[:2].lower() == exp["language"][:2].lower()

            if got["action"]:
                r["action_ok"] = got["action"] == exp["action"]

            if got["reply"]:
                r["invented_prices"] = invented_prices(got["reply"], allowed)

            notes = []
            if r.get("safety_ok") is False:
                notes.append("SAFETY FLAG MISSED")
            if r.get("slots_ok") is False:
                notes.append(f"slots {got['missing_slots']}")
            if r.get("language_ok") is False:
                notes.append(f"lang {got['language']}")
            if r.get("invented_prices"):
                notes.append(f"invented £{r['invented_prices']}")
            flags = ",".join(sorted(real_flags(got["safety_flags"]))) or "-"
            conf = f"{got['confidence']:.2f}" if got["confidence"] is not None else ""
            print(f"{case['id']:4} {exp['category']:24} {got['category']:24} "
                  f"{'✓' if r['category_ok'] else '✗':3} {conf:5} {flags[:18]:18} {'; '.join(notes)}")

        results.append(r)
        if i < len(cases) - 1:
            time.sleep(args.delay)

    # ---- summary
    scored = [r for r in results if r["got"]]

    def rate(key):
        xs = [r[key] for r in scored if key in r]
        return (sum(xs), len(xs)) if xs else (0, 0)

    cat = rate("category_ok")
    safe = rate("safety_ok")
    act = rate("action_ok")
    with_reply = [r for r in scored if "invented_prices" in r]
    invented = sum(1 for r in with_reply if r["invented_prices"])
    costs = [r["got"]["cost_usd"] for r in scored]

    print("\n" + "=" * 100)
    print(f"Category accuracy   {cat[0]}/{cat[1]}" + (f"  ({cat[0] / cat[1]:.0%})" if cat[1] else ""))
    print(f"Safety flags        {safe[0]}/{safe[1]}" if safe[1] else "Safety flags        —")
    print(f"Action accuracy     {act[0]}/{act[1]}" if act[1] else
          "Action accuracy     not scored yet — `action` is written in session 2")
    print(f"Invented prices     {invented}/{len(with_reply)} replies" if with_reply else
          "Invented prices     not scored yet — replies aren't stored in the `reply` table")
    print(f"Mean cost/enquiry   ${sum(costs) / len(costs):.6f}" if costs else "Mean cost/enquiry   —")
    failed = sum(1 for r in results if r.get("verdict") == "failed")
    missing = len(results) - len(scored) - failed
    if failed:
        print(f"Failed runs         {failed} case(s) — in dead_letter; replay with test/replay.py")
    if missing:
        print(f"No row written      {missing} case(s) — look in n8n → Executions for the failure")

    out_dir = HERE / "results"
    out_dir.mkdir(exist_ok=True)
    out = out_dir / f"{run}.jsonl"
    out.write_text("".join(json.dumps(r) + "\n" for r in results))
    print(f"\nFull results: {out.relative_to(ROOT)}")

    failed = False
    if any(r.get("safety_ok") is False for r in scored):
        print("FAIL: at least one safety case was not flagged.")
        failed = True
    if cat[1] and cat[0] / cat[1] < args.min_accuracy:
        print(f"FAIL: category accuracy below {args.min_accuracy:.0%}.")
        failed = True
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
